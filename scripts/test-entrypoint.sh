#!/bin/sh
# Проверка entrypoint.sh без Docker: системные команды (sysctl, ip, mknod) и пути
# (/dev/net/tun, /etc/resolv.conf, /usr/bin/awgd) подменяются во временном каталоге.
# Сценарии: Docker (sysctl уже заданы, tmpfs) и RouterOS (sysctl задаёт сам
# entrypoint, лишние ip rule, чужой resolv.conf, старые конфиги на диске).
set -eu
here=$(cd "$(dirname "$0")/.." && pwd)
fail=0
ok()   { printf 'ok   %s\n' "$*"; }
bad()  { printf 'FAIL %s\n' "$*"; fail=1; }

run_case() {
    name="$1"; preset="$2"
    t=$(mktemp -d); mkdir -p "$t/bin" "$t/run" "$t/dev"
    # «устройство» tun: обычный файл вместо символьного, проверку -c подменяем ниже
    : > "$t/dev/tun"
    printf 'nameserver 10.0.0.1\n' > "$t/resolv.conf"
    printf 'PrivateKey = секрет\n' > "$t/run/old.conf"
    # sysctl: хранит значения в файлах; в RouterOS-сценарии исходно 0
    mkdir -p "$t/sys"
    printf '%s' "$preset" > "$t/sys/net.ipv4.ip_forward"
    printf '%s' "$preset" > "$t/sys/net.ipv4.conf.all.src_valid_mark"
    printf '0' > "$t/sys/net.ipv6.conf.all.forwarding"
    printf '0' > "$t/sys/net.ipv4.fib_multipath_hash_policy"
    printf '0' > "$t/sys/net.ipv6.fib_multipath_hash_policy"
    printf '%s' "$((1 - preset))" > "$t/sys/net.ipv6.conf.all.disable_ipv6"
    cat > "$t/bin/sysctl" <<S
#!/bin/sh
if [ "\$1" = "-n" ]; then cat "$t/sys/\$2" 2>/dev/null; exit; fi
if [ "\$1" = "-w" ]; then k=\${2%%=*}; v=\${2#*=}; printf '%s' "\$v" > "$t/sys/\$k"; exit 0; fi
exit 1
S
    # ip rule: в RouterOS-сценарии есть лишнее «lookup main» с приоритетом 10
    # и нет «lookup local» (так было на CHR после обновления до 0.9.0)
    if [ "$preset" = 0 ]; then printf '10:\tfrom all lookup main\n32766:\tfrom all lookup main\n32767:\tfrom all lookup default\n' > "$t/rules"
    else printf '0:\tfrom all lookup local\n32766:\tfrom all lookup main\n32767:\tfrom all lookup default\n' > "$t/rules"; fi
    cat > "$t/bin/ip" <<S
#!/bin/sh
case "\$*" in
  "-4 rule show") cat "$t/rules" ;;
  "-6 rule show") printf '0:\tfrom all lookup local\n' ;;
  "-o -4 route show default") echo "default via 192.168.253.1 dev eth0 proto static" ;;
  "-o -4 route show default dev eth0") echo "default via 192.168.253.1 dev eth0 proto static" ;;
  "-o -4 addr show dev eth0") echo "2: eth0    inet 192.168.253.2/30 brd 192.168.253.3 scope global eth0" ;;
  "-6 -o addr show dev eth0 scope global") [ "$preset" = 1 ] && echo "2: eth0    inet6 2001:db8::2/64 scope global" ;;
  "-4 rule del priority "*) p=\$5; grep -v "^\$p:" "$t/rules" > "$t/rules.n"; mv "$t/rules.n" "$t/rules"; echo "del \$p" >> "$t/ip.log" ;;
  *) echo "\$*" >> "$t/ip.log" ;;
esac
S
    printf '#!/bin/sh\necho "awgd $*" > "%s/started"\n' "$t" > "$t/bin/awgd"
    chmod +x "$t/bin/"*
    sed -e "s#/dev/net/tun#$t/dev/tun#g" -e "s#\[ ! -c #[ ! -e #" \
        -e "s#/etc/resolv.conf#$t/resolv.conf#g" -e "s#/usr/bin/awgd#$t/bin/awgd#" \
        "$here/entrypoint.sh" > "$t/entrypoint.sh"
    if ! PATH="$t/bin:$PATH" RUN_DIR="$t/run" sh "$t/entrypoint.sh" --flag > "$t/out" 2>&1; then
        bad "$name: entrypoint завершился с ошибкой"; cat "$t/out"; rm -rf "$t"; return
    fi
    [ -f "$t/started" ] && grep -q -- "--flag" "$t/started" && ok "$name: awgd запущен с аргументами" || bad "$name: awgd не запущен"
    [ "$(cat "$t/sys/net.ipv4.ip_forward")" = 1 ] && ok "$name: ip_forward=1" || bad "$name: ip_forward"
    [ "$(cat "$t/sys/net.ipv4.conf.all.src_valid_mark")" = 1 ] && ok "$name: src_valid_mark=1" || bad "$name: src_valid_mark"
    [ "$(cat "$t/sys/net.ipv4.fib_multipath_hash_policy")" = 1 ] && [ "$(cat "$t/sys/net.ipv6.fib_multipath_hash_policy")" = 1 ] \
        && ok "$name: fib_multipath_hash_policy=1 (группы делят потоки по портам)" || bad "$name: fib_multipath_hash_policy"
    [ ! -e "$t/run/old.conf" ] && ok "$name: старые конфиги с ключами удалены" || bad "$name: old.conf остался"
    [ "$(stat -c %a "$t/run")" = 700 ] && ok "$name: RUN_DIR 0700" || bad "$name: права RUN_DIR"
    head -1 "$t/resolv.conf" | grep -q '^# Generated by resolvconf' && grep -q 'nameserver 10.0.0.1' "$t/resolv.conf" \
        && ok "$name: resolv.conf подготовлен для openresolv" || bad "$name: resolv.conf"
    [ "$(cat "$t/sys/net.ipv6.conf.all.forwarding")" = 1 ] && ok "$name: пересылка IPv6 включена" || bad "$name: ipv6 forwarding"
    [ "$(cat "$t/sys/net.ipv6.conf.eth0.accept_ra" 2>/dev/null)" = 2 ] && ok "$name: accept_ra=2 на LAN" || bad "$name: accept_ra"
    if [ "$preset" = 0 ]; then
        grep -q '^-4 rule add priority 0 lookup local$' "$t/ip.log" && ok "$name: пропавшее правило lookup local возвращено" || bad "$name: lookup local не возвращено: $(cat "$t/ip.log")"
        grep -q '^del 10$' "$t/ip.log" 2>/dev/null && ok "$name: лишнее правило lookup main удалено" || bad "$name: ip rule 10 не удалено"
        grep -q '^-6 addr add fd00:192:168:253::2/64 dev eth0$' "$t/ip.log" && grep -q '^-6 route add default via fd00:192:168:253::1 dev eth0 metric 2048$' "$t/ip.log" \
            && ok "$name: ULA fd00:192:168:253::2/64 выведен из IPv4" || bad "$name: ULA: $(cat "$t/ip.log")"
    else
        ! grep -qv '^-6 \(addr\|route\) add' "$t/ip.log" 2>/dev/null && ! grep -q 'addr add' "$t/ip.log" 2>/dev/null \
            && ok "$name: при глобальном IPv6 ULA не добавляется, ip rule не тронуты" || bad "$name: лишние вызовы ip: $(cat "$t/ip.log")"
    fi
    rm -rf "$t"
}

run_off() {
    t=$(mktemp -d); mkdir -p "$t/bin" "$t/sys" "$t/run"; : > "$t/tun"
    for k in net.ipv4.ip_forward net.ipv4.conf.all.src_valid_mark; do printf 1 > "$t/sys/$k"; done
    printf 1 > "$t/sys/net.ipv6.conf.all.forwarding"; printf 0 > "$t/sys/net.ipv6.conf.all.disable_ipv6"
    printf '#!/bin/sh\nif [ "$1" = -n ]; then cat "%s/sys/$2" 2>/dev/null; exit; fi\nk=${2%%%%=*}; v=${2#*=}; printf %%s "$v" > "%s/sys/$k"\n' "$t" "$t" > "$t/bin/sysctl"
    printf '#!/bin/sh\nexit 0\n' > "$t/bin/ip"; printf '#!/bin/sh\n: > "%s/started"\n' "$t" > "$t/bin/awgd"; chmod +x "$t/bin/"*
    sed -e "s#/dev/net/tun#$t/tun#g" -e "s#\[ ! -c #[ ! -e #" -e "s#/etc/resolv.conf#$t/none#g" -e "s#/usr/bin/awgd#$t/bin/awgd#" "$here/entrypoint.sh" > "$t/e.sh"
    PATH="$t/bin:$PATH" RUN_DIR="$t/run" AWG_ENABLE_IPV6=off sh "$t/e.sh" >/dev/null 2>&1 || true
    [ "$(cat "$t/sys/net.ipv6.conf.all.forwarding")" = 0 ] && [ "$(cat "$t/sys/net.ipv6.conf.all.disable_ipv6")" = 1 ] && [ -f "$t/started" ] \
        && ok "AWG_ENABLE_IPV6=off: IPv6 выключен, awgd запущен" || bad "AWG_ENABLE_IPV6=off"
    rm -rf "$t"
}

run_case "Docker (sysctl заданы)" 1
run_case "RouterOS (sysctl не заданы)" 0
run_off
exit $fail
